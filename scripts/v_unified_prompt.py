"""v2+v4+v5 3단 파이프라인을 단일 프롬프트로 통합 시도한 버전.
프롬프트 텍스트는 사용자가 지정한 원문 그대로(수정 금지)."""

import re

CATEGORIES = ["환불요청", "주문취소", "불만제기", "배송확인", "교환반품", "구매진행", "서비스이용"]

PROMPT_TEMPLATE_UNIFIED = """[지시문]
당신은 전자상거래(온라인 교육 플랫폼) 고객센터 상담 통화를 분석하는 전문가입니다.
아래 통화 전체 내용을 읽고, 고객의 실제 니즈(콜 전체를 통해 드러나는 핵심 용건)를
다음 7개 카테고리 중 하나로 분류하세요.

[분류 절차]
먼저 항의 여부를 판단한 뒤, 항의가 아니면 나머지 카테고리로 분류합니다.

■ 1단계 — 항의(불만제기) 여부
다음과 같은 항의성 신호가 뚜렷하면 "불만제기"로 분류합니다:
- 이전 통화/약속 불이행 지적 ("지난번에 해준다고 했는데", "몇 번을 전화했는지 아세요")
- 처리 지연에 대한 명시적 불만 ("한 달이 넘어가는데 왜")
- 응대 방식에 대한 직접적 비판 ("일방적으로 처리하시니까")
- 반복 압박·감정적 강조 ("당연히 되야 되는 거 아니에요?")
※ 단순 반복 접촉(재문의)만으로는 항의가 아님 — 어조가 담담하고 사실 확인
  위주면 항의 아님.
※ 표면적으로 환불요청·배송확인처럼 보여도, 본질이 위와 같은 항의이면
  불만제기로 분류할 것. (겉보기 용건보다 항의 본질이 우선)

■ 2단계 — 항의가 아니면 아래 6개 중 하나
1. 환불요청: 결제한 금액을 돌려받는 것이 최종 목적인 경우
   - "취소/반품/반송" 단어가 나와도, 절차의 최종 목적이 금전 반환(현금/캐시)이면 환불요청
   - 예: "책 취소하고 환불받고 싶어요", "재결제하고 전체 카드취소 해주세요"(재결제는 절차)
2. 주문취소: 배송/수강 전 상태에서, 환불 절차 없이 순수하게 주문을 무르는 경우
   - 환불요청과 차이: 수령한 물건의 반송·환불 절차가 없고 순수 주문 취소만 해당
   - 예: "어제 주문한 거 아직 배송 전인데 취소하고 싶어요"
3. 배송확인: 배송 상태·도착·송장 문의
   - 예: "탭이 아직 안 오고 있어서 언제쯤 오나 싶어서요"
4. 교환반품: 불량·오배송으로 물건을 다른 물건으로 교체 (금전 반환 아니라 물건↔물건)
   - 예: "파본이 돼서 왔어요", "색이 잘못돼서 교환하려고요"
5. 구매진행: 결제 완료를 위한 도움 요청
   - 예: "결제가 안 돼서요", "쿠폰 적용이 안 돼요"
6. 서비스이용: 로그인·기기·앱·시스템 이용 관련 문제
   - 재구매 제약, 시스템 오류 확인 등 결제와 무관한 절차 문제, 실질 용건 없이
     종료되는 경우 포함
   - 결제/재구매가 실제 진행되지 않고 시스템 문제 해결이 최종 목적이면
     구매진행이 아닌 서비스이용
   - 예: "윈도우 환경에서만 재생된다고 떠서요"

[판단 원칙]
- 여러 절차(취소→재결제 등)가 언급돼도, "이 통화에서 고객이 최종적으로 원하는
  결과"를 기준으로 분류할 것
- 초반과 후반 표현이 다르면, 전체 맥락에서 더 우세하게 실행/확정된 액션 기준으로 판단
- 통화가 지나치게 짧거나 실질 용건이 안 드러나면 서비스이용으로 분류

[통화 전체 내용]
{call_text}

[질문]
위 7개 카테고리 중 하나로만 답하세요. 카테고리명만 정확히 출력하고,
다른 설명은 추가하지 마세요.
"""


def make_prompt(call_text: str) -> str:
    return PROMPT_TEMPLATE_UNIFIED.format(call_text=call_text)


def normalize_gpt_label(raw: str) -> str:
    return re.sub(r"^\s*\d+[.)]\s*", "", str(raw)).strip()


