"""v5 프롬프트: v4의 1단계(항의 게이트)에서 has_complaint=False로 확정된 콜만
대상으로, 게이트 없이 순수 6개 카테고리 분류만 다시 수행하는 프롬프트.
v2의 카테고리 정의 + 판단 원칙을 복원한 버전 (v3처럼 우선순위 규칙을 끼워넣지
않고, 애초에 항의 콜을 대상에서 제외했으므로 규칙 자체가 필요 없음).
"""

import re

CATEGORIES_V5 = ["환불요청", "주문취소", "배송확인", "교환반품", "구매진행", "서비스이용"]

PROMPT_TEMPLATE_V5 = """[지시문]
아래 통화 전체 내용을 읽고, 고객의 실제 니즈를 다음 6개 카테고리 중 하나로 분류하세요.

1. 환불요청: 결제한 금액을 돌려받는 것이 최종 목적인 경우
   - "취소", "반품", "반송"이라는 단어가 나와도, 그 절차의 최종 목적이
     금전 반환(현금/캐시)이면 환불요청으로 분류할 것
   - 예: "재결제하고 전체 카드취소 해주세요" (재결제는 절차일 뿐)

2. 주문취소: 배송/수강 전, 환불 절차 없이 순수 주문 취소
   - 예: "어제 주문한 거 아직 배송 전인데 취소하고 싶어요"

3. 배송확인: 배송 상태·도착 문의
4. 교환반품: 불량·오배송 → 물건↔물건 교체 (금전 반환 아님)
5. 구매진행: 결제 완료를 위한 도움 요청
6. 서비스이용: 로그인·기기·앱·시스템 이용 문제

[판단 원칙]
- 통화 중 여러 절차(취소→재결제 등)가 언급되어도, "이 통화에서 고객이 최종적으로
  원하는 결과"를 기준으로 분류할 것
- 통화 초반 표현과 후반 표현이 다르면, 통화 전체 맥락에서 더 우세하게
  실행/확정된 액션을 기준으로 판단할 것

[통화 전체 내용]
{call_text}

[질문]
위 6개 카테고리 중 하나로만 답하세요. 카테고리명만 출력.
"""


def make_prompt(call_text: str) -> str:
    return PROMPT_TEMPLATE_V5.format(call_text=call_text)


def normalize_gpt_label(raw: str) -> str:
    return re.sub(r"^\s*\d+[.)]\s*", "", str(raw)).strip()


