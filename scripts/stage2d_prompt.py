def make_prompt(rows, with_acoustic: bool, version: str = "base") -> str:
    """version: 'base'(안내 없음, 기존과 100% 동일) | 'kr_full' | 'kr_slim' | 'v2' | 'v3' | 'v4'.
    with_acoustic=False면 version과 무관하게 안내문 없음(음성 서술 자체가 없으므로).
    v3/v4는 [질문] 섹션도 태그 출력 형식으로 교체됨(파싱은 호출부에서 태그 기반으로)."""
    n = len(rows)
    utterance_block = format_utterance_block(rows, with_acoustic)
    voice_guide = VOICE_GUIDE_BY_VERSION.get(version, "") if with_acoustic else ""
    question_block = QUESTION_BY_VERSION.get(version, QUESTION_DEFAULT)
    return PROMPT_HEADER.format(
        n=n, category_definitions=CATEGORY_DEFINITIONS, voice_guide=voice_guide,
        utterance_block=utterance_block, question_block=question_block,
    )


