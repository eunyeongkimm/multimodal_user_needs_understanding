def format_utterance_block(rows, with_acoustic: bool) -> str:
    """rows: dict 리스트, 각 dict는 {'speaker_group':..., 'text_clean':..., 'nl_description':...}
    dialog_idx(발화 순서) 오름차순으로 미리 정렬되어 있어야 한다."""
    lines = []
    for i, row in enumerate(rows, start=1):
        speaker = row["speaker_group"]
        text = row["text_clean"] or "(내용 없음)"
        line = f"발화{i}({speaker}): {text}"
        if with_acoustic:
            line += f"\n  [음성 특징: {row['nl_description']}]"
        lines.append(line)
    return "\n".join(lines)


